# 2. 将用户输入的10个字符串, 反转后全部转换为大写, 然后记录在列表中, 最后将列表内容，遍历输出出来。
s_list = []
for i in range(2):
    s = input(f"输入第{i + 1}个字符串:")
    s_list.append(s[::-1].upper())
print("输出的字符串列表：")
for i in s_list:
    print(i)
